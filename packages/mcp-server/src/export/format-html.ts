// --- Primitives -------------------------------------------------------------

function esc(value: unknown): string {
  const s = value == null ? "" : String(value);
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/** Home-directory + project-root stripping so a shared page never carries the
 *  exporter's username or machine layout. Repo-relative paths pass through. */
export function sanitizePath(raw: unknown, projectRoot?: string): string {
  let p = typeof raw === "string" ? raw.trim() : "";
  if (!p) return "";
  const normalized = p.replace(/\\/g, "/");
  if (projectRoot) {
    const root = projectRoot.replace(/\\/g, "/").replace(/\/+$/, "");
    if (root && normalized.startsWith(root + "/")) return normalized.slice(root.length + 1);
    if (root && normalized === root) return ".";
  }
  p = normalized;
  // F2 — collapse the user's home directory wherever it sits in the path.
  // The old anchored form (`^(?:[A-Za-z]:)?/(home|Users)/<u>/`) missed the
  // layout this project is DEVELOPED on: WSL's /mnt/c/Users/<u>/... sailed
  // through verbatim, putting the exporter's username in a page written to be
  // sent to strangers — and --redact-code cannot help, because the path IS the
  // leak. It covers /mnt/c/Users/<u>/, /cygdrive/c/Users/<u>/, C:/Users/<u>/
  // and plain /home/<u>/ alike.
  //
  // R3 — but F2's fix was `^.*?/(home|Users)/[^/]+/`, whose `.*?` matched ANY
  // prefix, including no prefix at all in a RELATIVE path. So a real repo path
  // — `app/views/home/partials/index.erb`, which every Rails app has — came
  // out of the sharing-hygiene helper as `~/index.erb`: three directories
  // deleted and a home directory invented, on the page a colleague reads to
  // find the file. The leak this collapses is only ever in an ABSOLUTE path,
  // so the pattern now names the absolute shapes it accepts (bare `/`, a
  // drive letter, a WSL/cygwin mount) instead of accepting anything.
  p = p.replace(HOME_PREFIX, "~/");
  return p;
}

/** The absolute-path shapes whose leading segments carry a username, for a
 *  path FIELD. sanitizePath normalizes backslashes to `/` before this runs, so
 *  it only ever sees forward slashes. Anchored, so a RELATIVE path containing a
 *  `home/` directory — `app/views/home/partials/index.erb` — is left exactly as
 *  written.
 *
 *  R3 (adversarial F2) — the prefix now covers every absolute shape, not just
 *  unix/mount: a drive letter (`C:/Users/<u>/`), and a UNC authority
 *  (`//fileserver/share/Users/<u>/`, `//wsl$/Ubuntu/home/<u>/`) — the latter
 *  leaked the internal HOSTNAME as well as the username. The home/Users segment
 *  must still sit at a KNOWN root position (directly after root, a drive, a
 *  mount, or a UNC host/share) so `/opt/build/home/<u>/` is deliberately NOT
 *  collapsed. */
const HOME_PREFIX =
  /^(?:[A-Za-z]:|\/\/[^/]+(?:\/[^/]+)?|(?:[A-Za-z]:)?\/(?:mnt|cygdrive)\/[A-Za-z])?\/(?:home|Users)\/[^/]+\//i;

// R3 (adversarial F2) — the PROSE scrubber is separator-agnostic: prose is not
// normalized, so a Windows path arrives with its backslashes intact. Built from
// named parts because a single literal of this is unreadable and unmaintainable.
//   - drive        `C:` (a `/Users` or `\Users` follows)
//   - backslash UNC `\\host` or `\\host\share` (covers `\\wsl$\Ubuntu` too)
//   - forward wsl   `//wsl$/distro` — the ONE forward-`//` form accepted, so a
//                   protocol-relative URL `//cdn/home/x` is never mistaken for
//                   a UNC authority
//   - mount         `/mnt/c`, `C:/cygdrive/c`
// then the `home|Users` segment. The leading lookbehind (excluding `\` too)
// keeps `views/home`, `https://x.com/home` and `/opt/build/home/<u>` as prose.
const _SEP = "[\\\\/]"; // one path separator, either kind
const _NOTSEG = "[^\\\\/\\s\"'`)\\]]"; // a char that can't be inside a path segment we scrub
const _HOME_PROSE_PREFIX =
  "(?:" +
  "[A-Za-z]:" +
  "|\\\\\\\\[^\\\\/\\s]+(?:\\\\[^\\\\/\\s]+)?" +
  "|//wsl\\$(?:/[^/\\s]+)?" +
  "|(?:[A-Za-z]:)?" + _SEP + "(?:mnt|cygdrive)" + _SEP + "[A-Za-z]" +
  ")?";
const HOME_PREFIX_IN_PROSE = new RegExp(
  "(?<![\\w~.\\-\\\\/])" +
    _HOME_PROSE_PREFIX +
    _SEP + "(?:home|Users)" + _SEP + _NOTSEG + "+" + _SEP,
  "gi",
);

// R3 — the project root for the page currently being rendered.
//
// Path FIELDS were scrubbed from the day this exporter shipped; PROSE was not.
// So `evidence.filePath` came out as `src/auth/hash.ts` while the narrative
// three inches above it — the agent's own writing, the part of the page a
// stranger actually reads — said "I traced it through
// /home/<username>/work/checkout/src/auth/hash.ts", shipping the exporter's
// username and machine layout into the artifact the whole feature exists to
// send out of the building.
//
// Every prose path funnels through renderInline / codeBlock / diff lines, none
// of which take a projectRoot argument (renderMarkdown is exported and widely
// called). Rather than thread a parameter through nine call sites and rely on
// nobody forgetting it at the tenth, the root is set once for the duration of
// one page render. formatSessionHtml is synchronous end to end — no await, no
// interleaving — and restores the previous value in a finally, so a nested
// render can never leak its root to the caller.
let activeProjectRoot: string | undefined;

/**
 * Collapse machine-identifying absolute paths out of PROSE.
 *
 * Same contract as sanitizePath, applied to free text: strip the project root
 * (the reader doesn't have it and it names the exporter's disk), then collapse
 * a home directory to `~/`. Everything else — relative paths, URLs, ordinary
 * sentences — is returned byte-identical.
 */
export function scrubProse(text: unknown, projectRoot = activeProjectRoot): string {
  let s = typeof text === "string" ? text : text == null ? "" : String(text);
  if (!s) return s;
  if (projectRoot) {
    const root = projectRoot.replace(/\\/g, "/").replace(/\/+$/, "");
    if (root) {
      // Literal split/join — a project root is a path, not a pattern, and
      // regex-escaping one is a bug waiting to happen. R3 (adversarial F2) —
      // strip BOTH the forward-slash form and the exporter's native backslash
      // form (`C:\proj\...`), since prose carries the path as the OS wrote it.
      const win = root.replace(/\//g, "\\");
      for (const r of win !== root ? [root, win] : [root]) {
        const sep = r === win ? "\\" : "/";
        if (s.includes(r + sep)) s = s.split(r + sep).join("");
        if (s.includes(r)) s = s.split(r).join(".");
      }
    }
  }
  return s.replace(HOME_PREFIX_IN_PROSE, "~/");
}

/** esc() for text that may carry a machine path — the scrub runs first so the
 *  escape sees the collapsed form. Used for every rendered body of prose or
 *  code; `esc` alone stays for ids, enums and chips. */
function escText(value: unknown): string {
  return esc(scrubProse(value));
}

function fmtTimestamp(iso?: string): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  return d.toISOString().replace("T", " ").slice(0, 16) + " UTC";
}

function fmtDay(iso?: string): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  return d.toISOString().slice(0, 10);
}

function plural(n: number, one: string, many = one + "s"): string {
  return `${n} ${n === 1 ? one : many}`;
}

// --- The tiny markdown renderer ---------------------------------------------
//
// Deliberately small and dependency-free (the page must build with zero new
// deps and stay self-contained). Covers what an agent-composed narrative
// actually uses: headings, paragraphs, bold/italic/inline-code, fenced code,
// bullet + numbered lists, blockquotes, links, and rules. Everything is
// ESCAPED first, so unmatched syntax degrades to literal text — never markup.

// F1 — ONE fence predicate, used by BOTH the block opener and the paragraph
// guard. They used to disagree: the opener demanded `^\s*```(\w+)?\s*$` while
// the paragraph loop refused any line starting ```. A line that starts a fence
// but fails the strict opener (```objective-c, ````, ```js title="x") then
// satisfied NEITHER — the cursor never advanced and renderMarkdown span-looped,
// allocating <p></p> forever. In the daemon that is a wedged export route AND a
// wedged daemon (the export is in-process). Any line whose first non-space run
// is 3+ backticks/tildes is a fence, full stop; whatever follows is the info
// string, and only its first token is treated as a language.
const FENCE_OPEN = /^\s*(?:`{3,}|~{3,})\s*([^\s`~]*)/;
const FENCE_CLOSE = /^\s*(?:`{3,}|~{3,})\s*$/;

// F8 — `//evil.example/x` is protocol-RELATIVE: a bare `^/` treated it as a
// same-page path and let a markdown link reach another host, which is exactly
// the property this page promises it doesn't have. `\/(?!\/)` keeps real
// root-relative paths and drops the two-slash form; explicit https:// links in
// a narrative are still allowed (the author meant them).
const SAFE_URL = /^(?:https?:\/\/|mailto:|#|\/(?!\/)|\.{1,2}\/)/i;

/**
 * R3 — links are found by a LINEAR SCAN, not a regex.
 *
 * The pattern this replaces — `/\[([^\]]+)\]\(([^)\s]+)\)/g` — is quadratic on
 * a run of `[`. At every one of the n opening brackets the engine scans the
 * whole remaining string for a `]` that isn't there, so the cost is n²/2:
 * measured at 8.0s of BLOCKED EVENT LOOP for a 120k-character comment (0.5s at
 * 30k — it degrades quietly, then falls off a cliff). The export runs
 * in-process in the daemon, so those seconds are the whole server: no UI, no
 * WebSocket, no other session, for as long as one pasted comment takes.
 *
 * Nobody writes a 120k-character link text, so the scan refuses to look for
 * one. The bail-out on the first line is what makes the pathological case
 * free: a string with no `](` in it cannot contain a link, and one indexOf
 * settles that in a single pass.
 */
const MAX_LINK_TEXT = 512;
const MAX_LINK_URL = 2048;

/** Bounded search for `ch` in `s` starting at `from`, giving up after `window`
 *  characters. R3 (adversarial F5) — a bare `s.indexOf(ch, from)` scans to the
 *  end of the string on every miss, which is the quadratic trap: `"[]("` * 400k
 *  has a `](` at every unit and NO `)` after it, so an unbounded search for the
 *  closing paren re-walked the whole tail 400k times (2.0s). The URL can't be
 *  longer than MAX_LINK_URL anyway, so there is nothing past the window worth
 *  finding. */
function indexOfWithin(s: string, ch: number, from: number, window: number): number {
  const limit = Math.min(s.length, from + window);
  for (let k = from; k < limit; k++) if (s.charCodeAt(k) === ch) return k;
  return -1;
}

function renderLinks(out: string): string {
  // A link REQUIRES a `](` seam AND a closing `)`. Two O(n) existence checks
  // rule out every string that can't contain a link — the 200k-`[` comment and
  // the 400k-`[](` comment (no `)` anywhere) both bail here in one pass.
  if (out.indexOf("](") < 0 || out.indexOf(")") < 0) return out;
  const parts: string[] = [];
  let pos = 0;
  while (pos < out.length) {
    const open = out.indexOf("[", pos);
    if (open < 0) break;
    const close = out.indexOf("]", open + 1);
    // No closing bracket anywhere ahead → no link can exist in the rest of the
    // string. Stop, rather than re-scanning the same tail for every `[` left.
    if (close < 0) break;
    if (close - open - 1 > MAX_LINK_TEXT) {
      // This `]` is too far to be this `[`'s partner, and it is the FIRST one
      // ahead, so every `[` before `close - MAX_LINK_TEXT` is equally hopeless.
      // Jump the cursor past them instead of retrying one character at a time —
      // that retry IS the quadratic term.
      const jump = Math.max(open + 1, close - MAX_LINK_TEXT);
      parts.push(out.slice(pos, jump));
      pos = jump;
      continue;
    }
    if (out.charCodeAt(close + 1) !== 40 /* ( */) {
      parts.push(out.slice(pos, close + 1));
      pos = close + 1;
      continue;
    }
    // Bounded — see indexOfWithin. `+ 1` so a URL of exactly MAX_LINK_URL still
    // finds its closing paren.
    const urlEnd = indexOfWithin(out, 41 /* ) */, close + 2, MAX_LINK_URL + 1);
    if (urlEnd < 0) {
      parts.push(out.slice(pos, close + 1));
      pos = close + 1;
      continue;
    }
    const label = out.slice(open + 1, close);
    const url = out.slice(close + 2, urlEnd);
    // Whitespace inside the target is not a URL (the old character class said
    // the same thing) — fall through and leave it as literal text.
    if (url.length === 0 || /\s/.test(url)) {
      parts.push(out.slice(pos, close + 1));
      pos = close + 1;
      continue;
    }
    const raw = url.replace(/&amp;/g, "&");
    parts.push(out.slice(pos, open));
    parts.push(
      SAFE_URL.test(raw) ? `<a href="${esc(raw)}" rel="noopener noreferrer">${label}</a>` : label,
    );
    pos = urlEnd + 1;
  }
  parts.push(out.slice(pos));
  return parts.join("");
}

function renderInline(text: string): string {
  // Escape first — every transform below operates on already-safe text.
  // R3 — the machine-path scrub runs BEFORE the escape, so the escape sees the
  // collapsed form and the two can never disagree about where the text ends.
  let out = escText(text);
  // Protect code spans from the emphasis passes.
  const codeSpans: string[] = [];
  out = out.replace(/`([^`]+)`/g, (_m, code: string) => {
    codeSpans.push(`<code>${code}</code>`);
    return `\u0000CODE${codeSpans.length - 1}\u0000`;
  });
  out = renderLinks(out);
  out = out.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
  out = out.replace(/(^|[^*\w])\*([^*\n]+)\*(?!\*)/g, "$1<em>$2</em>");
  out = out.replace(/(^|[^_\w])_([^_\n]+)_(?![\w_])/g, "$1<em>$2</em>");
  out = out.replace(/\u0000CODE(\d+)\u0000/g, (_m, i: string) => codeSpans[Number(i)] ?? "");
  return out;
}

/**
 * Render a markdown subset to HTML. `baseHeading` is the level a top-level `#`
 * maps to (the narrative sits under an <h2>, so its own headings start at h3
 * and the document outline stays sane).
 *
 * F4 — `includeCode: false` strips FENCED blocks here too. Prose reaches this
 * renderer from comments, narratives and summaries, and a human pasting a diff
 * into a comment is exactly the case the redaction contract ("strips every code
 * body") has to cover. Inline `code spans` stay: they are prose — identifiers
 * and flags, not bodies.
 */
export function renderMarkdown(md: string, baseHeading = 3, includeCode = true, depth = 0): string {
  // R3 — the LAST-RESORT guard. Every known way this renderer could blow up is
  // fixed below (the fence loop in F1, the blockquote recursion and the link
  // scan here), but the failure MODE is what makes a guard worth having: this
  // function runs in-process in the daemon, on text a human pasted, for a route
  // that has no other error path. When it threw, GET /api/export.html returned
  // 500 — and kept returning 500, because the comment that caused it is
  // persisted. The session's shareable page was dead permanently, and the UI
  // blamed the daemon ("is the daemon still running?"), so the one thing the
  // human could act on was the one thing they were never told.
  //
  // Degrading to escaped plain text loses formatting for one block. Losing the
  // page loses the feature.
  try {
    return renderMarkdownBlocks(md, baseHeading, includeCode, depth);
  } catch (err) {
    // R3 (adversarial F10) — a real renderer bug must not vanish silently, and
    // the fallback itself must not re-throw. escText runs the scrub regex, which
    // in principle can throw, so it is guarded; if even esc fails the block is
    // dropped rather than propagated. The tell (a console.warn + a visible
    // labelled block) means "the export renderer hit a bug here" reaches a
    // developer instead of looking like ordinary prose.
    try {
      // eslint-disable-next-line no-console
      console.warn("[deepPairing] renderMarkdown fell back to plain text:", (err as Error)?.message ?? err);
    } catch { /* logging must never fail the export */ }
    let safe = "";
    try { safe = escText(md); } catch { try { safe = esc(md); } catch { safe = ""; } }
    return `<p class="render-fallback" data-render-error="1">${safe}</p>`;
  }
}

/**
 * R3 — how deep blockquotes may nest before the rest is shown literally.
 *
 * The blockquote branch recurses once per leading `>`, so a comment that is a
 * run of `>` characters recurses once per CHARACTER. At 4,096 of them — a
 * plausible paste, and trivial to type — V8 threw RangeError: Maximum call
 * stack size exceeded, which is not catchable-and-forgettable when it happens
 * mid-page: the whole export died.
 *
 * 8 is well past any real quoting depth (a quote of a quote of a quote is
 * already unusual); beyond it the remaining `>` characters are rendered as
 * what they are — text — with no claim that they were anything else.
 */
const MAX_QUOTE_DEPTH = 8;

function renderMarkdownBlocks(md: string, baseHeading: number, includeCode: boolean, depth: number): string {
  const lines = String(md ?? "").replace(/\r\n?/g, "\n").split("\n");
  // noUncheckedIndexedAccess is on repo-wide: read every line through `at`.
  const at = (k: number): string => lines[k] ?? "";
  const out: string[] = [];
  let i = 0;

  const flushList = (tag: "ul" | "ol", items: string[]) => {
    out.push(`<${tag}>`);
    for (const item of items) out.push(`<li>${renderInline(item)}</li>`);
    out.push(`</${tag}>`);
  };

  while (i < lines.length) {
    const line = at(i);

    if (/^\s*$/.test(line)) { i++; continue; }

    // Fenced code (F1 — same predicate the paragraph guard uses, so the two
    // can never disagree about what a fence is).
    const fence = line.match(FENCE_OPEN);
    if (fence) {
      const body: string[] = [];
      i++;
      while (i < lines.length && !FENCE_CLOSE.test(at(i))) { body.push(at(i)); i++; }
      i++; // closing fence (or EOF — an unterminated fence still terminates)
      // Only a bare word is a language; an info string like `js title="x"`
      // contributes its first token, and anything else contributes nothing.
      const info = fence[1] ?? "";
      const language = /^[A-Za-z0-9_+-]+$/.test(info) ? info : undefined;
      out.push(codeBlock(body.join("\n"), { language, maxLines: MAX_CODE_LINES, includeCode }));
      continue;
    }

    // Horizontal rule
    if (/^\s*(?:-{3,}|\*{3,}|_{3,})\s*$/.test(line)) { out.push("<hr />"); i++; continue; }

    // Heading
    const h = line.match(/^\s*(#{1,6})\s+(.*)$/);
    if (h) {
      const level = Math.min(6, baseHeading + (h[1] ?? "#").length - 1);
      out.push(`<h${level}>${renderInline((h[2] ?? "").trim())}</h${level}>`);
      i++;
      continue;
    }

    // Blockquote
    if (/^\s*>\s?/.test(line)) {
      const body: string[] = [];
      while (i < lines.length && /^\s*>\s?/.test(at(i))) {
        body.push(at(i).replace(/^\s*>\s?/, ""));
        i++;
      }
      // R3 — depth-capped (see MAX_QUOTE_DEPTH). At the cap the remainder is
      // rendered LITERALLY rather than dropped: the reader still sees every
      // character the author typed, just not as more nesting.
      if (depth >= MAX_QUOTE_DEPTH) {
        out.push(`<blockquote class="quote-deep"><p>${escText(body.join("\n"))}</p></blockquote>`);
        continue;
      }
      out.push(
        `<blockquote>${renderMarkdown(body.join("\n"), baseHeading, includeCode, depth + 1)}</blockquote>`,
      );
      continue;
    }

    // Unordered list
    if (/^\s*[-*+]\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*[-*+]\s+/.test(at(i))) {
        items.push(at(i).replace(/^\s*[-*+]\s+/, ""));
        i++;
      }
      flushList("ul", items);
      continue;
    }

    // Ordered list
    if (/^\s*\d+[.)]\s+/.test(line)) {
      const items: string[] = [];
      while (i < lines.length && /^\s*\d+[.)]\s+/.test(at(i))) {
        items.push(at(i).replace(/^\s*\d+[.)]\s+/, ""));
        i++;
      }
      flushList("ol", items);
      continue;
    }

    // Paragraph
    const para: string[] = [];
    while (
      i < lines.length &&
      !/^\s*$/.test(at(i)) &&
      !FENCE_OPEN.test(at(i)) &&
      !/^\s*#{1,6}\s+/.test(at(i)) &&
      !/^\s*>/.test(at(i)) &&
      !/^\s*[-*+]\s+/.test(at(i)) &&
      !/^\s*\d+[.)]\s+/.test(at(i))
    ) {
      para.push(at(i));
      i++;
    }
    // F1 belt-and-braces: if the paragraph loop consumed NOTHING the cursor
    // must still move, or a future guard/opener mismatch becomes a hang again
    // instead of one odd-looking line. Never remove this.
    if (para.length === 0) { para.push(at(i)); i++; }
    out.push(`<p>${renderInline(para.join("\n"))}</p>`);
  }

  return out.join("\n");
}

// --- Code rendering ---------------------------------------------------------

interface CodeBlockOptions {
  language?: string;
  maxLines?: number;
  /** false → the body is replaced by an honest "code omitted" note. */
  includeCode?: boolean;
  label?: string;
}

/**
 * R3 — the WHOLE-PAGE size bound.
 *
 * Every cap in this file was per-thing (40 snippet lines, 400 diff lines per
 * file) and none of them multiplied: 60 changesets × 40 files × 500 diff lines
 * produced a 210 MB single HTML file. That isn't a big page, it's an
 * unopenable one — and the daemon builds it in memory, in-process, before it
 * can find out how big it got.
 *
 * So the code bodies (which are where essentially all the bytes are) draw from
 * one shared budget for the page. When it runs out, further bodies are replaced
 * by an explicit note and COUNTED, so the page can say how much it dropped
 * instead of quietly ending. Structure — every artifact, every file name, every
 * comment, the whole timeline — is never charged and never dropped: the record
 * of what happened survives at full fidelity, only the code inside it collapses.
 */
const SOFT_PAGE_CAP_BYTES = 5 * 1024 * 1024;

// R3 (adversarial F3) — a per-BODY hard cap and a per-LINE cap, because the
// original bound was per-file-LINE-COUNT and checked `remaining > 0` (any
// positive amount) then charged AFTER emitting. A single 20 MB minified diff
// line — a `min.js` in a changeset is Tuesday — passed the `remaining > 0`
// gate, emitted its whole 20 MB, THEN drove remaining negative, so the page was
// 20 MB and, adding insult, rendered the honest-truncation note as if it had
// protected anything. Now a body is truncated to fit BEFORE it is emitted, and
// no single line may exceed MAX_LINE_LEN.
const HARD_BODY_CAP = 256 * 1024;
const MAX_LINE_LEN = 4 * 1024;

interface RenderBudget {
  /** Characters of code body left to spend on this page. */
  remaining: number;
  /** How many bodies were collapsed because a cap (page or per-body) hit. */
  truncated: number;
}

// Set for the duration of one formatSessionHtml call — same single-threaded,
// finally-restored discipline as activeProjectRoot above.
let activeBudget: RenderBudget | undefined;

/** Cap one already-escaped body to what the page can still afford AND to the
 *  per-body ceiling, BEFORE it is emitted. Returns the (possibly clipped) text
 *  and whether anything was dropped — the caller appends the size note only
 *  when `sizeTruncated`, so a page that never hit a cap carries no note. */
function fitBody(body: string): { text: string; sizeTruncated: boolean } {
  if (!activeBudget) return { text: body, sizeTruncated: false };
  if (activeBudget.remaining <= 0) {
    activeBudget.truncated++;
    return { text: "", sizeTruncated: true };
  }
  const cap = Math.min(activeBudget.remaining, HARD_BODY_CAP);
  if (body.length > cap) {
    activeBudget.remaining -= cap;
    activeBudget.truncated++;
    return { text: body.slice(0, cap), sizeTruncated: true };
  }
  activeBudget.remaining -= body.length;
  return { text: body, sizeTruncated: false };
}

/** Is there any page budget left at all? (The cheap pre-check a diff runs
 *  before building rows.) Counts the refusal so the page can report it. */
function budgetHasRoom(): boolean {
  if (!activeBudget) return true;
  if (activeBudget.remaining <= 0) {
    activeBudget.truncated++;
    return false;
  }
  return true;
}

/** Clip one line to MAX_LINE_LEN so a single pathological line can't blow the
 *  per-body cap in one go (and can't force horizontal scroll to Kansas). */
function clipLine(text: string): string {
  return text.length > MAX_LINE_LEN ? text.slice(0, MAX_LINE_LEN) : text;
}

const SIZE_TRUNCATED_NOTE =
  `<p class="redacted">Truncated for size — this page had already reached its ` +
  `${Math.round(SOFT_PAGE_CAP_BYTES / (1024 * 1024))} MB budget when this block was reached. ` +
  `The full record is in the session itself.</p>`;

const SIZE_CLIPPED_NOTE =
  `<span class="truncated">… truncated for size — the rest of this block is in the session itself.</span>`;

/** A legible, syntax-highlight-free pre/mono block with an honest truncation
 *  marker. `includeCode: false` keeps the shape, drops the body. */
function codeBlock(text: string, opts: CodeBlockOptions = {}): string {
  const { language, maxLines = MAX_CODE_LINES, includeCode = true, label } = opts;
  const head = label ? `<p class="code-label">${escText(label)}</p>` : "";
  if (includeCode === false) {
    const lineCount = String(text ?? "").split("\n").length;
    return `${head}<p class="redacted">Code omitted from this export (${plural(lineCount, "line")}).</p>`;
  }
  const all = String(text ?? "").replace(/\r\n?/g, "\n").split("\n");
  const shown = all.slice(0, maxLines);
  const omitted = all.length - shown.length;
  // R3 — scrubbed, not just escaped: a snippet lifted out of a file on the
  // exporter's disk carries that disk's paths in its own text. Each line is
  // clipped (F3) so one pathological line can't blow the body cap — and a clip
  // is a truncation, so it must show the honest note too.
  const lineClipped = shown.some((l) => l.length > MAX_LINE_LEN);
  const body = escText(shown.map(clipLine).join("\n"));
  const fitted = fitBody(body);
  if (fitted.text === "" && fitted.sizeTruncated) return `${head}${SIZE_TRUNCATED_NOTE}`;
  const trunc = omitted > 0
    ? `\n<span class="truncated">… truncated — ${plural(omitted, "more line")} not shown</span>`
    : "";
  const sizeTrunc = fitted.sizeTruncated || lineClipped ? `\n${SIZE_CLIPPED_NOTE}` : "";
  const langAttr = language ? ` data-language="${esc(language)}"` : "";
  return `${head}<pre class="code"${langAttr}><code>${fitted.text}${trunc}${sizeTrunc}</code></pre>`;
}

/** Per-file unified diff. Long diffs collapse behind <details> rather than
 *  being cut, so the page stays skimmable without losing the record. */
function diffBlock(file: ChangesetFile, includeCode: boolean, projectRoot?: string): string {
  const path = sanitizePath(file.path, projectRoot);
  const changeType = esc(file.changeType ?? "modified");
  const hunks = Array.isArray(file.hunks) ? file.hunks : [];
  const stats = file.stats;
  const derived = hunks.reduce(
    (acc, h) => {
      for (const l of h?.lines ?? []) {
        if (l?.kind === "add") acc.additions++;
        else if (l?.kind === "del") acc.deletions++;
      }
      return acc;
    },
    { additions: 0, deletions: 0 },
  );
  const additions = stats?.additions ?? derived.additions;
  const deletions = stats?.deletions ?? derived.deletions;
  const statLine =
    `<span class="diffstat"><span class="add">+${additions}</span> <span class="del">−${deletions}</span></span>`;

  const header =
    `<div class="file-head"><code class="path">${esc(path)}</code>` +
    `<span class="chip chip--${changeType}">${changeType}</span>${statLine}</div>`;

  if (!includeCode) {
    return `<div class="file">${header}<p class="redacted">Diff omitted from this export.</p></div>`;
  }

  // R3 — a diff is the single biggest thing this page renders, so it asks the
  // page budget BEFORE building 400 rows it may not be able to keep, then
  // charges what it actually emitted.
  if (!budgetHasRoom()) {
    return `<div class="file">${header}${SIZE_TRUNCATED_NOTE}</div>`;
  }

  // R3 (F3) — the per-file char budget: the smaller of what the page can still
  // afford and the per-body ceiling. Rows stop the moment the running total
  // crosses it, so a `min.js` diff with one 20 MB line can't blow the page.
  const charCap = activeBudget ? Math.min(activeBudget.remaining, HARD_BODY_CAP) : Infinity;
  const rows: string[] = [];
  let emitted = 0;
  let dropped = 0;
  let chars = 0;
  let sizeTruncated = false;
  outer: for (const hunk of hunks) {
    if (hunk?.header) {
      rows.push(`<div class="dl dl--hunk">${escText(clipLine(hunk.header))}</div>`);
    }
    for (const line of hunk?.lines ?? []) {
      if (emitted >= MAX_DIFF_LINES_PER_FILE) { dropped++; continue; }
      const kind = line?.kind === "add" ? "add" : line?.kind === "del" ? "del" : "ctx";
      const sign = kind === "add" ? "+" : kind === "del" ? "-" : " ";
      const num = kind === "del" ? line?.oldLine : line?.newLine;
      const raw = line?.content ?? "";
      if (raw.length > MAX_LINE_LEN) sizeTruncated = true; // a clipped line is a truncation
      const row =
        `<div class="dl dl--${kind}"><span class="ln">${num == null ? "" : esc(num)}</span>` +
        `<span class="sign">${sign}</span><span class="src">${escText(clipLine(raw))}</span></div>`;
      if (chars + row.length > charCap) { sizeTruncated = true; break outer; }
      rows.push(row);
      chars += row.length;
      emitted++;
    }
  }
  if (dropped > 0) {
    rows.push(`<div class="dl dl--trunc">… truncated — ${plural(dropped, "more diff line")} not shown</div>`);
  }
  if (sizeTruncated) {
    rows.push(`<div class="dl dl--trunc">… truncated for size — the rest of this diff is in the session itself.</div>`);
  }

  const diff = `<div class="diff">${rows.join("")}</div>`;
  // Charge what was actually emitted; a wholly-dropped diff still counts as a
  // truncation for the page's honest note.
  if (activeBudget) {
    activeBudget.remaining -= chars;
    if (sizeTruncated) activeBudget.truncated++;
  }
  const body = emitted > DIFF_COLLAPSE_THRESHOLD
    ? `<details><summary>Show the diff (${plural(emitted, "line")})</summary>${diff}</details>`
    : diff;
  return `<div class="file">${header}${body}</div>`;
}

// --- Visuals ----------------------------------------------------------------
//
// R3 (the round-13 rider) — format-html rendered NO visuals for ANY type. A
// pair spends a session drawing a diagram, comments on regions of it, decides
// on the strength of it — and the page written to explain that session to
// someone who wasn't there dropped the picture entirely, silently. Round 13
// measured diagrams as the ONE comprehension instrument with proven organic
// engagement, which makes it the worst possible thing to drop.
//
// S4 (round-14) REVISITED whether to render Mermaid to a static inline SVG at
// export time (the picture, not its source) — the preferred outcome. It does
// not hold up: mermaid@11's `render()` needs a real browser DOM. Driven with
// happy-dom (the only DOM lib in the tree) it returns an EMPTY svg — the
// SVG-namespace serialization and zero text metrics (getBBox → 0) produce
// nothing usable — and a faithful render needs a headless Chromium (puppeteer /
// mermaid-cli) which is an unacceptably heavy+fragile dependency to launch
// inside the daemon's export path on arbitrary (possibly hostile) diagram
// source. So we keep the SOURCE — but make the framing honest and PROMINENT: a
// line that names it as source and says exactly where to see it drawn, plus the
// Mermaid source in a labelled block. The picture is PRESENT and named instead
// of absent and unmentioned, and the page keeps its promise (zero requests, no
// scripts, XSS-safe — escText escapes the source).
function visualsBlock(visuals: unknown, ctx: RenderCtx): string {
  if (!Array.isArray(visuals) || visuals.length === 0) return "";
  const parts: string[] = [];
  for (const raw of visuals) {
    if (!raw || typeof raw !== "object") continue;
    const v = raw as {
      kind?: string; title?: string; caption?: string; source?: string;
      files?: Array<{ path?: string; change?: string; note?: string }>;
      code?: string; filePath?: string; language?: string; lineStart?: number;
      annotations?: Array<{ line?: number; note?: string }>;
    };
    const title = v.title ? escText(v.title) : "";
    const caption = v.caption ? `<p class="visual-caption">${renderInline(v.caption)}</p>` : "";
    let body = "";
    let kindLabel = "";
    switch (v.kind) {
      case "diagram": {
        kindLabel = "Diagram";
        const src = String(v.source ?? "").trim();
        // R3×R4 seam — the Mermaid source is a code body like any other, so it
        // must obey `includeCode: false` (`--redact-code`). Otherwise a secret
        // that lived only in a diagram's source survives redaction while the
        // secret banner promises the opposite ("any secret that lived only in
        // code isn't shown here"). Keep the diagram PRESENT and named — its
        // title/caption already render above — but drop the source, mirroring
        // the annotated_code branch's redaction note.
        body = src
          ? ctx.includeCode
            ? `<p class="visual-note">A diagram the pair drew and discussed. This page runs no ` +
              `scripts, so it can't draw the picture here — the Mermaid source it was drawn from ` +
              `is below. Paste it into deepPairing, or any Mermaid viewer (e.g. mermaid.live), to ` +
              `see it rendered.</p>` +
              `<details class="visual-source" open><summary>Diagram source (Mermaid)</summary>` +
              `<pre class="code" data-language="mermaid"><code>${escText(src)}</code></pre></details>`
            : `<p class="visual-note">A diagram the pair drew and discussed. It is drawn in deepPairing.</p>` +
              `<p class="redacted">Diagram source omitted from this export.</p>`
          : `<p class="visual-note">A diagram was attached here, but its source was not recorded.</p>`;
        break;
      }
      case "file_map": {
        kindLabel = "File map";
        const rows = (v.files ?? [])
          .map((f) => {
            const p = sanitizePath(f?.path, ctx.projectRoot);
            if (!p) return "";
            const change = f?.change ? `<span class="chip chip--${esc(f.change)}">${esc(f.change)}</span>` : "";
            const note = f?.note ? ` — ${renderInline(f.note)}` : "";
            return `<li><code>${esc(p)}</code>${change}${note}</li>`;
          })
          .filter(Boolean)
          .join("");
        body = rows ? `<ul class="visual-files">${rows}</ul>` : "";
        break;
      }
      case "annotated_code": {
        kindLabel = "Annotated code";
        const p = sanitizePath(v.filePath, ctx.projectRoot);
        body =
          (p ? `<p class="anchor"><code>${esc(p)}</code></p>` : "") +
          codeBlock(v.code ?? "", {
            language: v.language,
            maxLines: MAX_SNIPPET_LINES,
            includeCode: ctx.includeCode,
          }) +
          ((v.annotations ?? []).length
            ? `<ul class="visual-annotations">${(v.annotations ?? [])
                .map((n) => `<li><code>line ${esc(n?.line ?? "?")}</code> ${renderInline(n?.note ?? "")}</li>`)
                .join("")}</ul>`
            : "");
        break;
      }
      case "prototype":
        kindLabel = "Prototype";
        // Never embedded: the prototype is arbitrary HTML, and this page's whole
        // promise is that it runs nothing and fetches nothing.
        body =
          `<p class="visual-note">An interactive prototype was attached here. It is not embedded — ` +
          `this page deliberately runs no scripts and makes no requests — so view it in deepPairing.</p>`;
        break;
      default:
        continue;
    }
    if (!body) continue;
    parts.push(
      `<div class="visual"><p class="visual-head"><span class="visual-kind">${esc(kindLabel)}</span>` +
      (title ? ` ${title}` : "") + `</p>${caption}${body}</div>`,
    );
  }
  return parts.join("");
}

// --- Evidence ---------------------------------------------------------------

function evidenceBlock(evidence: unknown, includeCode: boolean, projectRoot?: string): string {
  if (!Array.isArray(evidence)) {
    if (typeof evidence === "string" && evidence.trim()) {
      return `<p class="evidence-note">${renderInline(evidence)}</p>`;
    }
    return "";
  }
  const parts: string[] = [];
  for (const ev of evidence) {
    if (typeof ev === "string") {
      if (ev.trim()) parts.push(`<p class="evidence-note">${renderInline(ev)}</p>`);
      continue;
    }
    if (!ev || typeof ev !== "object") continue;
    const e = ev as Evidence;
    const path = sanitizePath(e.filePath, projectRoot);
    const range = e.lineStart != null
      ? `:${e.lineStart}${e.lineEnd != null && e.lineEnd !== e.lineStart ? `-${e.lineEnd}` : ""}`
      : "";
    const anchor = path ? `<p class="anchor"><code>${esc(path + range)}</code></p>` : "";
    const snippet = e.snippet
      ? codeBlock(e.snippet, { language: e.language, maxLines: MAX_SNIPPET_LINES, includeCode })
      : "";
    const explanation = e.explanation ? `<p class="evidence-note">${renderInline(e.explanation)}</p>` : "";
    parts.push(`<div class="evidence">${anchor}${snippet}${explanation}</div>`);
  }
  return parts.join("");
}

// --- Comments ---------------------------------------------------------------

/** Human-readable "where this comment landed", from the comment target. */
function anchorLabel(c: Comment, projectRoot?: string): string {
  const t = (c.target ?? {}) as CommentTarget;
  const bits: string[] = [];
  if (t.filePath) {
    const line = t.lineStart ?? t.lineNumber;
    bits.push(`${sanitizePath(t.filePath, projectRoot)}${line != null ? `:${line}` : ""}${t.side === "old" ? " (removed line)" : ""}`);
  } else if (t.lineStart != null || t.lineNumber != null) {
    bits.push(`line ${t.lineStart ?? t.lineNumber}`);
  }
  if (t.findingIndex != null) bits.push(`finding #${t.findingIndex + 1}`);
  if (t.evidenceIndex != null) bits.push(`evidence #${t.evidenceIndex + 1}`);
  if (t.stepIndex != null) bits.push(`step ${t.stepIndex + 1}`);
  if (t.requirementId) bits.push(`requirement ${t.requirementId}`);
  if (t.optionId) bits.push(`option ${t.optionId}`);
  if (t.questionIndex != null) bits.push(`open question #${t.questionIndex + 1}`);
  if (t.sectionId) bits.push(`section ${t.sectionId}`);
  if (t.visualId) bits.push(t.region ? "a region of the diagram" : "the diagram");
  if (Array.isArray(t.anchors) && t.anchors.length > 1) bits.push(`${t.anchors.length} linked locations`);
  return bits.join(" · ");
}

function commentHtml(c: Comment, includeCode: boolean, projectRoot?: string): string {
  const who = c.author === "agent" ? "The agent" : "The human";
  const intent = c.intent;
  const intentChip = intent && intent !== "comment"
    ? `<span class="chip chip--${esc(intent)}">${esc(intent)}</span>`
    : "";
  const anchor = anchorLabel(c, projectRoot);
  const anchorHtml = anchor ? `<span class="thread-anchor">on ${esc(anchor)}</span>` : "";
  const sug = c.suggestion;
  let sugHtml = "";
  if (sug) {
    const state = sug.state ? `<span class="chip chip--${esc(sug.state)}">suggestion ${esc(sug.state)}</span>` : "";
    const replacement = sug.replacementText
      ? codeBlock(sug.replacementText, { includeCode, maxLines: MAX_SNIPPET_LINES, label: "Suggested instead" })
      : "";
    const counter = sug.counter?.replacementText
      ? codeBlock(sug.counter.replacementText, { includeCode, maxLines: MAX_SNIPPET_LINES, label: "The agent's counter" })
      : "";
    const counterReason = sug.counter?.reason ? `<p>${renderInline(sug.counter.reason)}</p>` : "";
    sugHtml = `<div class="suggestion">${state}${replacement}${counter}${counterReason}</div>`;
  }
  return (
    `<li class="thread-item thread-item--${c.author === "agent" ? "agent" : "human"}">` +
    `<div class="thread-meta"><span class="who">${esc(who)}</span>${intentChip}${anchorHtml}` +
    `<time>${esc(fmtTimestamp(c.createdAt))}</time></div>` +
    `<div class="thread-body">${renderMarkdown(c.content ?? "", 5, includeCode)}</div>${sugHtml}</li>`
  );
}

function threadHtml(comments: Comment[], includeCode: boolean, projectRoot?: string, heading = "Discussion"): string {
  if (comments.length === 0) return "";
  const items = comments
    .slice()
    .sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)))
    .map((c) => commentHtml(c, includeCode, projectRoot))
    .join("");
  return `<div class="thread"><h4 class="thread-head">${esc(heading)} (${comments.length})</h4><ul class="thread-list">${items}</ul></div>`;
}

// --- Artifact bodies --------------------------------------------------------

interface RenderCtx {
  state: HtmlSessionState;
  includeCode: boolean;
  projectRoot?: string;
  /** artifactId → comments, minus any already rendered under a diff file. */
  commentsByArtifact: Map<string, Comment[]>;
}

function researchBody(a: Artifact, ctx: RenderCtx): string {
  const content = coerceResearchContent(a.content);
  const parts: string[] = [];
  if (content.summary) parts.push(renderMarkdown(content.summary, 4, ctx.includeCode));
  // R4 P-B (#284) — the visuals the research was framed by (see visualsBlock).
  parts.push(visualsBlock(content.visuals, ctx));
  for (const f of content.findings ?? []) {
    // significance (note-worthiness) and severity (risk) are DIFFERENT axes
    // that often carry the same word — name each so two "HIGH" chips beside
    // each other don't read as a duplicate.
    const sig = f.significance ? `<span class="chip chip--sig-${esc(f.significance)}">${esc(f.significance)} significance</span>` : "";
    const sev = f.severity ? `<span class="chip chip--sev-${esc(f.severity)}">${esc(f.severity)} severity</span>` : "";
    const cat = f.category ? `<span class="chip">${esc(f.category)}</span>` : "";
    // R4 P-A (#284) — the named pattern behind this finding travels to the share
    // page too (same "Pattern:" treatment as decision options / debrief sections).
    const concept = f.concept?.name
      ? `<p class="concept">Pattern: <strong>${esc(f.concept.name)}</strong>` +
        (f.concept.oneLineExplanation ? ` — ${renderInline(f.concept.oneLineExplanation)}` : "") +
        `</p>`
      : "";
    parts.push(
      `<div class="finding"><h4>${escText(f.title ?? f.category ?? "Finding")}</h4>` +
      `<div class="chips">${sig}${sev}${cat}</div>` +
      renderMarkdown(f.detail ?? "", 5, ctx.includeCode) + concept +
      evidenceBlock(f.evidence, ctx.includeCode, ctx.projectRoot) +
      (f.impact ? `<p class="kv"><span class="k">Impact</span> ${renderInline(f.impact)}</p>` : "") +
      (f.recommendation ? `<p class="kv"><span class="k">Recommendation</span> ${renderInline(f.recommendation)}</p>` : "") +
      `</div>`,
    );
  }
  for (const q of content.openQuestions ?? []) {
    parts.push(`<p class="open-question">Open question: ${renderInline(q)}</p>`);
  }
  return parts.join("");
}

