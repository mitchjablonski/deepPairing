export function formatSessionHtml(state: HtmlSessionState, options: HtmlExportOptions = {}): string {
  const includeCode = options.includeCode !== false;
  const generatedAt = options.generatedAt ?? new Date().toISOString();
  const version = options.version ?? "";
  const projectName = options.projectName ?? "";
  const projectRoot = options.projectRoot;

  const artifactIds = new Set(state.artifacts.map((a) => a.id));
  const commentsByArtifact = new Map<string, Comment[]>();
  const looseComments: Comment[] = [];
  for (const c of state.comments ?? []) {
    const id = c.target?.artifactId;
    if (id && artifactIds.has(id)) {
      const list = commentsByArtifact.get(id) ?? [];
      list.push(c);
      commentsByArtifact.set(id, list);
    } else {
      looseComments.push(c);
    }
  }

  const ctx: RenderCtx = { state, includeCode, projectRoot, commentsByArtifact };

  const events = buildTimeline({
    artifacts: state.artifacts,
    comments: state.comments,
    decisions: state.decisions as DecisionRecord[],
    planReviews: state.planReviews as PlanReviewRecord[],
  });

  const artifactById = new Map(state.artifacts.map((a) => [a.id, a]));
  const beats: Beat[] = [];
  let seq = 0;

  for (const event of events) {
    switch (event.kind) {
      case "artifact_created": {
        const a = event.artifactId ? artifactById.get(event.artifactId) : undefined;
        if (a) beats.push(artifactBeat(a, ctx, seq++));
        break;
      }
      case "artifact_status_changed":
        beats.push(statusBeat(event, seq++));
        break;
      case "decision_resolved":
        beats.push(decisionBeat(event, seq++));
        break;
      case "plan_reviewed":
        beats.push(planReviewBeat(event, seq++));
        break;
      case "comment_added":
        // Comments on an artifact render INSIDE that artifact's card (anchored
        // where they happened); only session-level comments become beats.
        break;
      default:
        break;
    }
  }

  for (const c of looseComments) beats.push(looseCommentBeat(c, ctx, seq++));

  const stances = state.sessionMemory?.rejectedApproaches ?? [];
  const timedStances = stances.filter((r) => !!r.rejectedAt);
  const untimedStances = stances.filter((r) => !r.rejectedAt);
  for (const r of timedStances) beats.push(stanceBeat(r, seq++));

  for (const t of state.preflightTraces ?? []) {
    const b = traceBeat(t, seq++);
    if (b) beats.push(b);
  }

  // Guardrail fires are PROJECT-scoped (hooks-state.json has no session id), so
  // only the ones inside this session's own window can honestly be claimed as
  // part of this story.
  const stamps = beats.map((b) => b.at).filter(Boolean).sort();
  const spanFirst = stamps[0];
  const spanLast = stamps[stamps.length - 1];
  for (const f of state.guardrailFires ?? []) {
    if (!f.at) continue;
    if (spanFirst && f.at < spanFirst) continue;
    if (spanLast && f.at > spanLast) continue;
    beats.push(guardrailBeat(f, seq++));
  }

  beats.sort((a, b) => {
    if (a.at && b.at && a.at !== b.at) return a.at.localeCompare(b.at);
    if (!a.at && b.at) return 1;
    if (a.at && !b.at) return -1;
    return a.seq - b.seq;
  });

  const allStamps = beats.map((b) => b.at).filter(Boolean).sort();
  const span = { first: allStamps[0], last: allStamps[allStamps.length - 1] };

  const title = sessionTitle(state);
  const story = options.narrative?.trim()
    ? renderMarkdown(options.narrative, 3)
    : autoSummary(state, span);

  const metaBits = [
    projectName ? `<span>Project: ${esc(projectName)}</span>` : "",
    `<span>Session: <code>${esc(state.sessionId)}</code></span>`,
    span.first ? `<span>${esc(fmtDay(span.first))} → ${esc(fmtDay(span.last))}</span>` : "",
    `<span>Exported ${esc(fmtDay(generatedAt))}</span>`,
    version ? `<span>deepPairing v${esc(version)}</span>` : "",
    includeCode ? "" : `<span>code omitted</span>`,
  ].filter(Boolean).join("");

  const audienceLine = options.audience?.trim()
    ? `<p class="audience">Written for ${esc(options.audience.trim())}.</p>`
    : "";

  const timeline = beats.length
    ? `<ol class="beats">${beats.map((b) => b.html).join("")}</ol>`
    : `<p class="open-question">Nothing was recorded in this session.</p>`;

  const stancesSection = untimedStances.length
    ? `<section><h2>Standing stances</h2>` +
      `<p>Recorded without a timestamp, so they can't be placed on the timeline — but the gate enforces them all the same.</p>` +
      `<ul class="stances">${untimedStances
        .map((r) => `<li><strong>${esc(r.description)}</strong>${r.reason ? ` — “${esc(r.reason)}”` : ""}${r.concept ? ` <code>${esc(r.concept)}</code>` : ""}</li>`)
        .join("")}</ul></section>`
    : "";

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="color-scheme" content="light dark" />
<meta name="generator" content="deepPairing${version ? ` ${esc(version)}` : ""}" />
<title>${esc(title)} — deepPairing session</title>
<style>${STYLES}</style>
</head>
<body>
<main class="page">
<header class="masthead">
<p class="eyebrow">deepPairing session</p>
<h1>${esc(title)}</h1>
${audienceLine}
<div class="meta">${metaBits}</div>
</header>

<section class="story">
<h2>What this was</h2>
${story}
</section>

<section class="timeline">
<h2>How it unfolded</h2>
${timeline}
</section>

${stancesSection}

<footer>
<span>Generated by deepPairing${version ? ` v${esc(version)}` : ""} — ${esc(fmtTimestamp(generatedAt))}</span>
<span><a href="${REPO_URL}" rel="noopener noreferrer">github.com/mitchjablonski/deepPairing</a></span>
</footer>
</main>
</body>
</html>
`;
}
