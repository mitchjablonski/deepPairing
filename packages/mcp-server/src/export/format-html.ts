function decisionBody(a: Artifact, ctx: RenderCtx): string {
  const content = coerceDecisionContent(a.content);
  const record = ctx.state.decisions.find(
    (d) => d.decisionId === content.decisionId || d.artifactId === a.id,
  );
  const chosenId = record?.response?.optionId;
  const parts: string[] = [];
  if (content.context) parts.push(renderMarkdown(content.context, 4, ctx.includeCode));
  parts.push(`<div class="options">`);
  for (const o of content.options ?? []) {
    const chosen = chosenId != null && o.id === chosenId;
    const badge = chosen
      ? `<span class="chip chip--chosen">chosen</span>`
      : chosenId != null
        ? `<span class="chip chip--notchosen">not taken</span>`
        : "";
    const rec = o.recommendation ? `<span class="chip">agent's pick</span>` : "";
    const pros = (o.pros ?? []).map((p) => `<li>${renderInline(p)}</li>`).join("");
    const cons = (o.cons ?? []).map((p) => `<li>${renderInline(p)}</li>`).join("");
    const concept = o.concept?.name
      ? `<p class="concept">Pattern: <strong>${esc(o.concept.name)}</strong>` +
        (o.concept.oneLineExplanation ? ` — ${renderInline(o.concept.oneLineExplanation)}` : "") +
        `</p>`
      : "";
    parts.push(
      `<div class="option${chosen ? " option--chosen" : ""}">` +
      `<div class="option-head"><h4>${escText(o.title ?? o.id)}</h4>${badge}${rec}</div>` +
      `<div class="chips"><span class="chip">effort: ${esc(o.effort ?? "?")}</span><span class="chip">risk: ${esc(o.risk ?? "?")}</span></div>` +
      (o.description ? `<p>${renderInline(o.description)}</p>` : "") + concept +
      visualsBlock((o as { visuals?: unknown }).visuals, ctx) +
      (pros ? `<p class="k">Pros</p><ul class="pros">${pros}</ul>` : "") +
      (cons ? `<p class="k">Cons</p><ul class="cons">${cons}</ul>` : "") +
      `</div>`,
    );
  }
  parts.push(`</div>`);
  if (record?.response) {
    const chosenOption = (content.options ?? []).find((o) => o.id === chosenId);
    parts.push(
      `<div class="verdict verdict--chosen"><strong>The human chose:</strong> ${escText(chosenOption?.title ?? chosenId ?? "")}` +
      (record.response.reasoning ? ` — “${renderInline(record.response.reasoning)}”` : "") +
      `</div>`,
    );
  } else {
    parts.push(`<p class="pending">No answer recorded for this fork.</p>`);
  }
  return parts.join("");
}

