// --- The page ---------------------------------------------------------------

export function formatSessionHtml(state: HtmlSessionState, options: HtmlExportOptions = {}): string {
  // R3 — the page-scoped render context (machine-path scrub + total size
  // budget). Set here, restored in the finally below, so a nested or
  // concurrent-looking call can never inherit or leak another page's settings.
  const previousRoot = activeProjectRoot;
  const previousBudget = activeBudget;
  activeProjectRoot = options.projectRoot;
  activeBudget = { remaining: SOFT_PAGE_CAP_BYTES, truncated: 0 };
  try {
    return renderSessionPage(state, options);
  } finally {
    activeProjectRoot = previousRoot;
    activeBudget = previousBudget;
  }
}

function renderSessionPage(state: HtmlSessionState, options: HtmlExportOptions): string {
  const includeCode = options.includeCode !== false;
  const generatedAt = options.generatedAt ?? new Date().toISOString();
  const version = options.version ?? "";
  const projectName = options.projectName ?? "";
  const projectRoot = options.projectRoot;

  const artifactIds = new Set(state.artifacts.map((a) => a.id));
  const commentsByArtifact = new Map<string, Comment[]>();
  const looseComments: Comment[] = [];
  for (const c of state.comments ?? []) {
    const id = c.target?.artifactId;
    if (id && artifactIds.has(id)) {
      const list = commentsByArtifact.get(id) ?? [];
      list.push(c);
      commentsByArtifact.set(id, list);
    } else {
      looseComments.push(c);
    }
  }

  const ctx: RenderCtx = { state, includeCode, projectRoot, commentsByArtifact };

  const events = buildTimeline({
    artifacts: state.artifacts,
    comments: state.comments,
    decisions: state.decisions as DecisionRecord[],
    planReviews: state.planReviews as PlanReviewRecord[],
  });

  const artifactById = new Map(state.artifacts.map((a) => [a.id, a]));
  const beats: Beat[] = [];
  let seq = 0;

  for (const event of events) {
    switch (event.kind) {
      case "artifact_created": {
        const a = event.artifactId ? artifactById.get(event.artifactId) : undefined;
        if (a) beats.push(artifactBeat(a, ctx, seq++));
        break;
      }
      case "artifact_status_changed":
        beats.push(statusBeat(event, seq++));
        break;
      case "decision_resolved":
        beats.push(decisionBeat(event, seq++));
        break;
      case "plan_reviewed":
        beats.push(planReviewBeat(event, seq++));
        break;
      case "comment_added":
        // Comments on an artifact render INSIDE that artifact's card (anchored
        // where they happened); only session-level comments become beats.
        break;
      default:
        break;
    }
  }

  for (const c of looseComments) beats.push(looseCommentBeat(c, ctx, seq++));

  const stances = state.sessionMemory?.rejectedApproaches ?? [];
  const timedStances = stances.filter((r) => !!r.rejectedAt);
  const untimedStances = stances.filter((r) => !r.rejectedAt);
  for (const r of timedStances) beats.push(stanceBeat(r, seq++));

  for (const t of state.preflightTraces ?? []) {
    const b = traceBeat(t, seq++);
    if (b) beats.push(b);
  }

  // Guardrail fires are PROJECT-scoped (hooks-state.json has no session id), so
  // only the ones inside this session's own window can honestly be claimed as
  // part of this story.
  const stamps = beats.map((b) => b.at).filter(Boolean).sort();
  const spanFirst = stamps[0];
  const spanLast = stamps[stamps.length - 1];
  for (const f of state.guardrailFires ?? []) {
    if (!f.at) continue;
    if (spanFirst && f.at < spanFirst) continue;
    if (spanLast && f.at > spanLast) continue;
    const gb = guardrailBeat(f, seq++);
    if (gb) beats.push(gb);
  }

  beats.sort((a, b) => {
    if (a.at && b.at && a.at !== b.at) return a.at.localeCompare(b.at);
    if (!a.at && b.at) return 1;
    if (a.at && !b.at) return -1;
    return a.seq - b.seq;
  });

  const allStamps = beats.map((b) => b.at).filter(Boolean).sort();
  const span = { first: allStamps[0], last: allStamps[allStamps.length - 1] };

  // R3 — the NARRATIVE's own first heading wins the title when the agent wrote
  // one (see narrativeTitle); sessionTitle's decision-first heuristic is the
  // fallback. R3 (adversarial F1) — the fallback MUST scrub: GET
  // /api/export.html passes no narrative, so on the Export-menu surface (a human
  // on the other end) sessionTitle always wins, and a decision context or spec
  // title carrying an absolute path would otherwise land in the tab, the
  // bookmark, the <h1> and the print header verbatim. narrativeTitle already
  // scrubs; the fallback did not.
  const title = narrativeTitle(options.narrative) ?? scrubProse(sessionTitle(state));
  const story = options.narrative?.trim()
    ? renderMarkdown(options.narrative, 3, includeCode)
    : autoSummary(state, span);

  const metaBits = [
    projectName ? `<span>Project: ${esc(projectName)}</span>` : "",
    // R3 — the session id is GONE from the masthead. It is
    // `session_<local folder name>_<hash>`: a directory off the exporter's
    // machine, printed on a page whose entire purpose is to be handed to
    // someone outside it, and useless to every reader who isn't the exporter.
    span.first ? `<span>${esc(fmtDay(span.first))} → ${esc(fmtDay(span.last))}</span>` : "",
    `<span>Exported ${esc(fmtDay(generatedAt))}</span>`,
    version ? `<span>deepPairing v${esc(version)}</span>` : "",
    includeCode ? "" : `<span>code omitted</span>`,
  ].filter(Boolean).join("");

  const audienceLine = options.audience?.trim()
    ? `<p class="audience">Written for ${esc(options.audience.trim())}.</p>`
    : "";

  const timeline = beats.length
    ? `<ol class="beats">${beats.map((b) => b.html).join("")}</ol>`
    : `<p class="open-question">Nothing was recorded in this session.</p>`;

  // R3 — the size bound's honest footnote. Rendered only when the page actually
  // hit the cap, so a normal export is byte-identical to before.
  const truncatedCount = activeBudget?.truncated ?? 0;
  const sizeNote = truncatedCount > 0
    ? `<p class="size-note">${plural(truncatedCount, "section was", "sections were")} truncated to keep this ` +
      `page a size a mail client and a browser can actually handle. Nothing was removed from the record ` +
      `itself — the session still has all of it.</p>`
    : "";

  // R3 — external-review provenance for the masthead (see provenanceBlock).
  const externals: Array<{ artifact: Artifact; source: PrProvenance }> = [];
  for (const a of state.artifacts ?? []) {
    const src = externalSourceOf(a);
    if (src) externals.push({ artifact: a, source: src });
  }
  const provenance = provenanceBlock(externals);

  // R3 — the last-moment secret warning, on the page itself. The MCP reply
  // reaches the agent and the toast reaches whoever clicked Export; NEITHER
  // reaches the person who opens the downloaded file an hour later and is about
  // to attach it to an email. Warn-only, always: refusing to render someone's
  // own session because a fixture contains AKIA… would be the tool overruling
  // the human on their own repo.
  const secretLabels = (options.secretLabels ?? []).filter((l) => typeof l === "string" && l.trim());
  // R3 (adversarial F4) — the headline number is the OCCURRENCE count, not the
  // deduped label list, so 40 keys read as 40, not 1. The label list stays
  // deduped for legibility.
  const secretCount = options.secretCount ?? secretLabels.length;
  // R3 (adversarial F6) — with code omitted, the "search the page for them"
  // instruction is a lie about anything that lived only in a code body; those
  // aren't on the page. Reword rather than mislead. A secret in the narrative or
  // a comment (prose, always rendered) survives redaction, so the list stays.
  const secretBanner = secretLabels.length
    ? `<div class="secret-banner" role="note">${SHIELD_MARK}` +
      `<p><strong>Check this page before you send it.</strong> The export scan matched ` +
      `${plural(secretCount, "credential-shaped value")} in this session's material: ` +
      `${secretLabels.map((l) => esc(l)).join(", ")}. ` +
      (includeCode
        ? `The values are not repeated here — search the page for them, and re-export with code omitted if they are real.`
        : `Code bodies were omitted from this page, so any secret that lived only in code isn't shown here — but check the prose (summaries, comments, the narrative) before sending.`) +
      `</p></div>`
    : "";

  // R3 (adversarial F11) — a clean page must not read as PROOF of no secrets.
  // When the scan ran (secretLabels is defined — [] means "scanned, clean";
  // undefined means "no scan wired", e.g. a raw formatSessionHtml test call)
  // state so, with the depth, so absence of a banner isn't mistaken for a
  // guarantee. Nothing shown when no scan ran, keeping those callers unchanged.
  const scanFootnote =
    options.secretLabels !== undefined
      ? `<span class="scan-note">Secret-shape scan ran before export (depth ${DEFAULT_SCAN_DEPTH}, heuristic — not a guarantee).</span>`
      : "";

  const stancesSection = untimedStances.length
    ? `<section><h2>Standing stances</h2>` +
      `<p>Recorded without a timestamp, so they can't be placed on the timeline — but the gate enforces them all the same.</p>` +
      `<ul class="stances">${untimedStances
        .map((r) => `<li><strong>${escText(r.description)}</strong>${r.reason ? ` — “${escText(r.reason)}”` : ""}${r.concept ? ` <code>${esc(r.concept)}</code>` : ""}</li>`)
        .join("")}</ul></section>`
    : "";

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="color-scheme" content="light dark" />
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'" />
<meta name="generator" content="deepPairing${version ? ` ${esc(version)}` : ""}" />
<title>${esc(title)} — deepPairing session</title>
<style>${STYLES}</style>
</head>
<body>
<main class="page">
<header class="masthead">
<p class="eyebrow">deepPairing session</p>
<h1>${esc(title)}</h1>
${audienceLine}
<div class="meta">${metaBits}</div>
${provenance}
</header>
${secretBanner}

<section class="story">
<h2>What this was</h2>
${story}
</section>

<section class="timeline">
<h2>How it unfolded</h2>
${timeline}
${sizeNote}
</section>

${stancesSection}

<footer>
<span>Generated by deepPairing${version ? ` v${esc(version)}` : ""} — ${esc(fmtTimestamp(generatedAt))}</span>
<span><a href="${REPO_URL}" rel="noopener noreferrer">github.com/mitchjablonski/deepPairing</a></span>
${scanFootnote}
</footer>
</main>
</body>
</html>
`;
}
