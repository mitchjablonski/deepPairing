function sessionTitle(state: HtmlSessionState): string {
  const liveDecision = state.decisions.find((d) => {
    const owner = state.artifacts.find((a) => a.id === d.artifactId);
    return !owner || !NOT_SHIPPED.has(owner.status);
  });
  if (liveDecision) return liveDecision.title?.trim() || liveDecision.context;
  const anchorTypes = ["spec", "research", "debrief", "plan", "changeset"];
  for (const type of anchorTypes) {
    const hit = state.artifacts.find((a) => a.type === type && !NOT_SHIPPED.has(a.status));
    if (hit?.title) return hit.title;
  }
  return `Session ${state.sessionId}`;
}

/** The fallback story when the agent supplied no narrative: counts, the
 *  decisions and how they landed, and the span the session covers. Labelled as
 *  auto-generated so nobody mistakes it for someone's writing. */
function autoSummary(state: HtmlSessionState, span: { first?: string; last?: string }): string {
  const byType = new Map<string, number>();
  for (const a of state.artifacts) byType.set(a.type, (byType.get(a.type) ?? 0) + 1);
  const typeList = Array.from(byType.entries())
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([t, n]) => `${n} ${esc(t)}${n === 1 ? "" : "s"}`)
    .join(", ");
  const resolved = state.decisions.filter((d) => d.response);
  const decisionList = resolved.length
    ? `<ul>${resolved
        .map((d) => {
          const chosen = d.options?.find?.((o) => o.id === d.response?.optionId);
          return `<li><strong>${esc(d.title?.trim() || d.context)}</strong> → ${esc(chosen?.title ?? d.response?.optionId ?? "")}` +
            (d.response?.reasoning ? ` — “${esc(d.response.reasoning)}”` : "") + `</li>`;
        })
        .join("")}</ul>`
    : `<p>No fork was put to the human in this session.</p>`;
  const spanLine = span.first
    ? `<p>The session runs from ${esc(fmtTimestamp(span.first))} to ${esc(fmtTimestamp(span.last))}.</p>`
    : "";
  const stances = state.sessionMemory?.rejectedApproaches ?? [];
  const stanceLine = stances.length
    ? `<p>${plural(stances.length, "approach was", "approaches were")} rejected and recorded — the gate blocks them from being re-proposed.</p>`
    : "";
  return (
    `<p class="auto-note">Auto-generated summary — no narrative was written for this export.</p>` +
    `<p>This session produced ${typeList || "no artifacts"}, ` +
    `${plural(state.comments.length, "comment")} and ${plural(resolved.length, "resolved decision")}.</p>` +
    spanLine + `<h3>Decisions</h3>` + decisionList + stanceLine
  );
}

