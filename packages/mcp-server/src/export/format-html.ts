function changesetBody(a: Artifact, ctx: RenderCtx, ownComments: Comment[]): string {
  const content = coerceChangesetContent(a.content);
  const parts: string[] = [];
  if (content.summary) parts.push(renderMarkdown(content.summary, 4, ctx.includeCode));
  if (content.risks?.length) {
    // R3 — risks are SENTENCES ("touches the auth path; the session cookie is
    // re-signed"), not one-word tags, and .chip is `white-space: nowrap`. An
    // 860px-wide pill forced the whole page into horizontal scroll on a phone —
    // the page most likely to be opened on one, since it arrives as a link in a
    // message. They render as wrapping pills instead, and the agent's markdown
    // backticks are stripped rather than printed as literal ` characters.
    parts.push(
      `<div class="chips chips--risk">${content.risks
        .map((r) => `<span class="chip chip--risk">${escText(String(r).replace(/`/g, ""))}</span>`)
        .join("")}</div>`,
    );
  }
  // R4 P-B (#284) — a changeset-level visual ("the shape of what this PR
  // touches"), before the per-file diffs it frames.
  parts.push(visualsBlock(content.visuals, ctx));
  for (const file of content.files ?? []) {
    const disposition = content.reviewState?.[file.path];
    const reason = content.reviewReasons?.[file.path];
    const dispHtml = disposition
      ? `<p class="disposition">Reviewed as <strong>${esc(disposition)}</strong>${reason ? ` — ${renderInline(reason)}` : ""}</p>`
      : "";
    // Comments anchored to THIS file render right under its diff — where they
    // happened — and are removed from the artifact's Discussion block.
    const fileComments = ownComments.filter((c) => c.target?.filePath === file.path);
    for (const c of fileComments) {
      const idx = ownComments.indexOf(c);
      if (idx >= 0) ownComments.splice(idx, 1);
    }
    parts.push(
      `<div class="file-wrap">${diffBlock(file, ctx.includeCode, ctx.projectRoot)}${dispHtml}` +
      threadHtml(fileComments, ctx.includeCode, ctx.projectRoot, "On this file") + `</div>`,
    );
  }
  return parts.join("");
}

