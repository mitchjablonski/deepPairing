/**
 * Q5 — the SHAREABLE session page (`html`, the seventh export format).
 *
 * The other six formats produce markdown you paste somewhere else. This one
 * produces ONE self-contained HTML file you can send to a colleague who wasn't
 * there: inline CSS, zero external requests (the only absolute URL on the page
 * is the footer's repo anchor), works straight off `file://`, respects
 * `prefers-color-scheme`, and prints.
 *
 * Structure (top to bottom):
 *   1. Masthead — project · session · exported-at · deepPairing version.
 *   2. The story — the AGENT-COMPOSED narrative (`narrative`, markdown), or an
 *      honestly-labelled auto-summary when none was supplied.
 *   3. The timeline — replay's chronological event assembly (`buildTimeline`),
 *      with each artifact rendered RICHLY (findings + evidence, decision cards
 *      with every option, spec/plan sections, changeset diffs) and the comment
 *      threads anchored where they happened.
 *   4. Standing stances — rejected approaches with no timestamp to place.
 *   5. Footer — "Generated by deepPairing".
 *
 * HONESTY RULES (the same ones format-markdown carries, restated for a page a
 * stranger reads):
 *   - Rejected / retracted / superseded work is NEVER silently included as if
 *     it shipped, and never silently dropped: its header is struck through and
 *     carries an explicit verdict line ("rejected — <reason>").
 *   - The gate beats render ONLY what the store actually records. Preflight
 *     BLOCKS are not persisted anywhere (the block returns before an artifact
 *     exists, so `preflight-traces.json` — keyed by artifact id — never sees
 *     them; round-12 confirmed the live block is a 12s toast). So the page
 *     renders (a) the STANCES themselves, from session memory, which ARE
 *     timestamped and are what the gate enforces from then on, (b) any
 *     persisted trace, including the `decision: "blocked"` shape should one
 *     ever be recorded, and (c) guardrail hook asks from `hooks-state.json`
 *     when the caller passes them. Nothing is invented.
 *
 * SHARING HYGIENE: absolute paths are relativized against the project root and
 * home-directory prefixes collapse to `~/`; code is INCLUDED by default (the
 * diffs are the point) but `includeCode: false` strips every code body while
 * keeping the file names and shapes.
 */
