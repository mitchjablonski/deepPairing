/**
 * A stance the human recorded — the gate moment made shareable. This is what
 * the preflight gate enforces from this instant on: a later paraphrase of the
 * same idea is refused before it can be proposed.
 */
function stanceBeat(r: HtmlRejectedApproach, seq: number): Beat {
  const reason = r.reason ? `<blockquote class="human-reason">${renderInline(r.reason)}</blockquote>` : "";
  const concept = r.concept
    ? `<p class="gate-note">Recorded as the concept <code>${esc(r.concept)}</code> — a paraphrase of the same idea is caught too.</p>`
    : "";
  return beat(
    r.rejectedAt ?? "",
    seq,
    `<li class="beat beat--gate"><time>${esc(fmtTimestamp(r.rejectedAt))}</time>` +
    `<h3>${BLOCK_MARK}Rejected — and remembered: ${escText(r.description)}</h3>` +
    reason + concept +
    `<p class="gate-note">From here on the agent is blocked from proposing this again.</p></li>`,
  );
}

/** A PERSISTED preflight trace. Blocked traces render as the ⛔ callout;
 *  admitted-with-near-miss traces render the quieter "the gate weighed this"
 *  breadcrumb. Nothing is synthesized — a session with no persisted traces
 *  produces no beats here. */
function traceBeat(t: HtmlPreflightTrace, seq: number): Beat | null {
  if (t.decision === "blocked" && t.block) {
    const reason = t.block.reason ? `<blockquote class="human-reason">${renderInline(t.block.reason)}</blockquote>` : "";
    return beat(
      t.at ?? "",
      seq,
      `<li class="beat beat--gate"><time>${esc(fmtTimestamp(t.at))}</time>` +
      `<h3>${BLOCK_MARK}The gate refused ${esc(t.toolName ?? "a proposal")}</h3>` +
      `<p>It matched a stance the human had already recorded${t.block.concept ? `: <code>${esc(t.block.concept)}</code>` : ""}.</p>` +
      reason + `<p class="gate-note">Source: ${esc(t.block.source ?? "session")} memory. The artifact was never created.</p></li>`,
    );
  }
  const near = (t.nearMisses ?? []).filter((n) => n?.concept);
  if (near.length === 0) return null;
  // R3 — `consideredCount` counts LOCAL stances only. The cross-project ledger
  // is advisory and lives outside it, so a trace whose near-miss came from
  // another project rendered as "The gate weighed 0 recorded stances" — at the
  // exact moment the gate had weighed something and said so. Zero is a claim,
  // and it was the wrong one. Count both sources, name each honestly.
  const globalNear = near.filter((n) => n.source === "global");
  const localCount = t.consideredCount ?? 0;
  let weighed: string;
  if (localCount > 0 && globalNear.length > 0) {
    weighed =
      `weighed ${plural(localCount, "stance")} recorded in this session, plus ` +
      `${plural(globalNear.length, "more")} carried over from another project,`;
  } else if (localCount > 0) {
    weighed = `weighed ${plural(localCount, "recorded stance")}`;
  } else if (globalNear.length > 0) {
    weighed = `weighed ${plural(globalNear.length, "stance")} carried over from another project`;
  } else {
    weighed = "weighed the stances on record";
  }
  return beat(
    t.at ?? "",
    seq,
    `<li class="beat beat--near"><time>${esc(fmtTimestamp(t.at))}</time>` +
    `<span class="beat-line">The gate ${weighed} before this and let it through — ` +
    `nearest call: ${near.map((n) => `<code>${esc(n.concept)}</code>`).join(", ")}.</span></li>`,
  );
}

/** A guardrail hook ask (`hooks-state.json`). Project-scoped and path-free by
 *  design — the record carries only `at`, `hook`, `reason` — so the beat says
 *  exactly that much and no more. */
function guardrailBeat(f: HtmlGuardrailFire, seq: number): Beat | null {
  // F3 — a guardrail ASK is the only fire this beat can honestly describe, and
  // readGuardrailFires already keeps nothing else. The old else-branch rendered
  // ANY fire as "the hook stopped the run... the human had to confirm" — which
  // turned the stop-hook's fail-open `{hook:"stop", reason:"owes debrief in
  // <sessionId>"}` (exit 0; nothing was stopped, nobody confirmed) into a
  // fabricated gate moment that also printed ANOTHER session's id onto a page
  // meant for strangers. Belt-and-braces: re-check here, and render nothing
  // rather than guess.
  const reason = String(f.reason ?? "");
  if (f.hook !== "preflight" || !reason.startsWith("guardrail:")) return null;
  const category = reason.slice("guardrail:".length);
  if (!category) return null;
  return beat(
    f.at ?? "",
    seq,
    `<li class="beat beat--guardrail"><time>${esc(fmtTimestamp(f.at))}</time>` +
    `<h3>${SHIELD_MARK}Guardrail ask</h3>` +
    `<p>The hook stopped the run because the agent was about to touch ` +
    `<strong>${esc(category)}</strong> work — the human had to confirm before it continued.</p></li>`,
  );
}

